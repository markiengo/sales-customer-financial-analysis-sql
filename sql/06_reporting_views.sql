/* 2. Product Report 
Metrics definition:
- total_orders: number of distinct orders containing the product
- total_sales: total revenue generated by the product
- total_quantity: total units sold
- total_customers: number of unique customers who purchased the product
- lifespan: number of months between first and last sale
- recency: months since most recent sale
- avg_order_value: average revenue per order containing the product
- avg_monthly_revenue: average revenue generated per month of activity */ 

create view report_products as
with base_query as (
    select
        s.order_number,
        s.product_key,
        s.order_date,
        s.sales_amount,
        s.quantity,
        p.product_number,
        p.product_name,
        p.category,
        p.subcategory,
        p.cost
    from sales as s
    left join products as p
        on p.product_key = s.product_key
    where s.order_date is not null
)
-- aggregations
, product_aggregation as (
    select
        product_key,
        product_number,
        product_name,
        category,
        subcategory,
        cost,
        count(distinct order_number) as total_orders,
        sum(sales_amount) as total_sales,
        sum(quantity) as total_quantity,
        max(order_date) as last_order_date,
        datediff(month, min(order_date), max(order_date)) as lifespan
    from base_query
    group by
        product_key,
        product_number,
        product_name,
        category,
        subcategory,
        cost
)
-- final results
select
    product_key,
    product_number,
    product_name,
    category,
    subcategory,
    cost,
    datediff(month, last_order_date, getdate()) as recency,
    total_orders,
    total_sales,
    total_quantity,
    lifespan,
    -- avo: average order value
    case when total_orders = 0 then 0
	else total_sales / total_orders
    end as avg_order_value,
    -- average monthly revenue
    case when lifespan = 0 then total_sales
    else total_sales / lifespan
    end as avg_monthly_revenue
from product_aggregation;



